// In-memory runtime cache for any dynamically extended locations
const dynamicCache = {
  cities: {},
  barangays: {}
};

/**
 * 0ms Instant Local Lookups for Cities/Municipalities
 */
export function getLocalCities(provinceName) {
  if (!provinceName) return [];
  const key = String(provinceName).trim().toUpperCase();
  const normalizedKey = normalizeKey(provinceName);

  // Exact or normalized key lookup
  for (const [prov, cities] of Object.entries(CITIES_BY_PROVINCE)) {
    if (prov === key || normalizeKey(prov) === normalizedKey) {
      return cities;
    }
  }

  // Check runtime cache
  if (dynamicCache.cities[normalizedKey]) {
    return dynamicCache.cities[normalizedKey];
  }

  return [];
}

/**
 * 0ms Instant Local Lookups for Barangays
 */
export function getLocalBarangays(cityName) {
  if (!cityName) return [];
  const formatted = formatCityName(cityName);
  const normalized = normalizeKey(cityName);

  for (const [cityKey, brgyList] of Object.entries(LOCAL_BARANGAYS_BY_CITY)) {
    if (cityKey === formatted || normalizeKey(cityKey) === normalized) {
      return brgyList;
    }
  }

  if (dynamicCache.barangays[normalized]) {
    return dynamicCache.barangays[normalized];
  }

  return [];
}

/**
 * Registers dynamically fetched address data into in-memory local cache
 */
export function cacheLocalAddressData(provinceName, citiesList = [], cityName = '', barangaysList = []) {
  if (provinceName && Array.isArray(citiesList) && citiesList.length > 0) {
    dynamicCache.cities[normalizeKey(provinceName)] = citiesList.map(formatCityName);
  }
  if (cityName && Array.isArray(barangaysList) && barangaysList.length > 0) {
    dynamicCache.barangays[normalizeKey(cityName)] = barangaysList.map(b => String(b).toUpperCase());
  }
}
