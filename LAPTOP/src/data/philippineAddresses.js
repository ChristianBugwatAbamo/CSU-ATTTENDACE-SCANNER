// Normalized helper
export function normalizeKey(str) {
  return String(str || '')
    .trim()
    .toUpperCase()
    .replace(/^CITY OF\s+/, '')
    .replace(/\s+CITY$/, '')
    .replace(/[^A-Z0-9]/g, '');
}

export function formatCityName(rawName) {
  if (!rawName) return '';
  let str = String(rawName).trim();
  if (/^city\s+of\s+/i.test(str)) {
    str = str.replace(/^city\s+of\s+/i, '').trim() + ' CITY';
  }
  return str.toUpperCase();
}

